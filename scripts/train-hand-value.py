"""Train a small trick-distribution network; export browser-readable weights."""
import copy
import hashlib
import json
import os
from pathlib import Path

import numpy as np
import torch
from torch import nn

torch.set_num_threads(4)
torch.manual_seed(719)
raw_data = Path(os.environ.get("TRAIN_DATA", "/tmp/preferans-training.jsonl")).read_text()
rows = [json.loads(line) for line in raw_data.splitlines()]
if len(rows) < 200 or len({r["seed"] for r in rows}) != len(rows):
    raise ValueError("Need at least 200 independently seeded examples, without duplicate seeds")
x = torch.tensor([r["features"] for r in rows], dtype=torch.float32)
y = torch.tensor([r["tricks"] for r in rows], dtype=torch.long)
order = np.random.default_rng(719).permutation(len(rows))
train, valid, test = np.split(order, [int(len(rows) * .8), int(len(rows) * .9)])
model = nn.Sequential(nn.Linear(x.shape[1], 96), nn.ReLU(), nn.Dropout(.12),
                      nn.Linear(96, 48), nn.ReLU(), nn.Linear(48, 11))
optimizer = torch.optim.AdamW(model.parameters(), lr=.0015, weight_decay=.015)
loss_fn = nn.CrossEntropyLoss(label_smoothing=.02)
best, best_epoch, best_state = float("inf"), 0, None
for epoch in range(240):
    model.train()
    shuffled = torch.tensor(train)[torch.randperm(len(train))]
    for batch in shuffled.split(256):
        optimizer.zero_grad()
        loss = loss_fn(model(x[batch]), y[batch])
        loss.backward()
        optimizer.step()
    model.eval()
    with torch.no_grad():
        val = nn.functional.cross_entropy(model(x[valid]), y[valid]).item()
    if val < best - .001:
        best, best_epoch, best_state = val, epoch, copy.deepcopy(model.state_dict())
    if epoch % 20 == 0:
        print(json.dumps({"epoch": epoch, "validationNll": val}), flush=True)
    if epoch - best_epoch > 30:
        break
model.load_state_dict(best_state)
model.eval()
with torch.no_grad():
    valid_logits = model(x[valid])
    temperature = min([.65, .8, 1., 1.15, 1.35, 1.6, 2.],
                      key=lambda t: nn.functional.cross_entropy(valid_logits / t, y[valid]).item())
    logits = model(x[test]) / temperature
    probs = logits.softmax(dim=1)
    expected = probs @ torch.arange(11, dtype=torch.float32)
    prior = torch.bincount(y[train], minlength=11).float() + 1
    prior /= prior.sum()
    report = {
        "games": len(rows), "train": len(train), "validation": len(valid), "test": len(test),
        "dataSha256": hashlib.sha256(raw_data.encode()).hexdigest(),
        "randomSeed": 719, "torchVersion": str(torch.__version__), "numpyVersion": str(np.__version__),
        "bestEpoch": best_epoch, "temperature": temperature,
        "testNll": nn.functional.cross_entropy(logits, y[test]).item(),
        "priorNll": -prior[y[test]].log().mean().item(),
        "testMeanAbsoluteTrickError": (expected - y[test]).abs().mean().item(),
        "priorMeanAbsoluteTrickError": ((prior @ torch.arange(11, dtype=torch.float32)) - y[test]).abs().mean().item(),
        "sixTrickBrierScore": ((probs[:, 6:].sum(dim=1) - (y[test] >= 6).float()) ** 2).mean().item(),
        "labelHistogram": torch.bincount(y, minlength=11).tolist(),
        "teacher": "Current medium bot with hidden-information sampling; both defenders whist, six-trick contracts",
        "scope": "Predicts post-discard trick distribution from own hand, private discard, trump and position. Predictive accuracy is not a claim of stronger game play.",
    }
layers = [{"weights": [[round(float(v), 6) for v in row] for row in layer.weight.detach()],
           "bias": [round(float(v), 6) for v in layer.bias.detach()]}
          for layer in model if isinstance(layer, nn.Linear)]
report["weightsSha256"] = hashlib.sha256(json.dumps(layers, separators=(",", ":")).encode()).hexdigest()
ranges = []
for seed in sorted(r["seed"] for r in rows):
    if ranges and seed == ranges[-1][1] + 1:
        ranges[-1][1] = seed
    else:
        ranges.append([seed, seed])
report["seedRanges"] = ranges
example = rows[int(test[0])]
artifact = {"version": 2, "features": int(x.shape[1]), "temperature": temperature,
            "layers": layers, "training": report,
            "parityCheck": {"hand": example["hand"], "discarded": example["discarded"],
                            "trump": example["trump"], "first": example["first"],
                            "probabilities": probs[0].tolist()}}
out = Path(os.environ.get("MODEL_OUTPUT", "src/hand-model.ts"))
temporary = out.with_suffix(".tmp")
temporary.write_text("// Generated by scripts/train-hand-value.py. Do not edit weights manually.\nexport const handModel = " +
                     json.dumps(artifact, separators=(",", ":")) + ";\n")
temporary.replace(out)
Path(os.environ.get("TRAIN_REPORT", "training-results.json")).write_text(json.dumps(report, indent=2) + "\n")
print(json.dumps(report, indent=2))
